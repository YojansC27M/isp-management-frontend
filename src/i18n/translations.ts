export const interpolateTranslation = (template: string, params?: Record<string, string | number>) => {
  if (!params) return template
  return Object.entries(params).reduce(
    (result, [key, value]) => result.replace(new RegExp(`\\{${key}\\}`, "g"), String(value)),
    template
  )
}

export const translateWithLocale = (
  locale: Locale,
  key: string,
  params?: Record<string, string | number>
) => {
  const message = translations[locale][key] ?? translations.es[key] ?? key
  return interpolateTranslation(message, params)
}

